-- Esquema de la base de datos (Postgres / Supabase).
-- Se puede ejecutar varias veces sin romper nada.
-- Las fechas se guardan en la hora local del negocio (sin zona horaria).
-- Si el negocio no está en Argentina, reemplazá 'America/Argentina/Buenos_Aires' en todo este
-- archivo por tu zona (ej: 'America/Montevideo') y cambiala también en src/negocio.ts.

create table if not exists productos (
  id integer generated by default as identity primary key,
  marca text not null default '',
  nombre text not null,
  sku text,
  costo numeric(14,2) not null default 0,
  precio numeric(14,2) not null default 0,
  precio_revendedor numeric(14,2),
  stock numeric(12,2) not null default 0,
  stock_minimo numeric(12,2) not null default 1,
  stock_ideal numeric(12,2) not null default 0,
  activo boolean not null default true,
  tn_product_id bigint,
  tn_variant_id bigint,
  creado timestamp not null default (now() at time zone 'America/Argentina/Buenos_Aires')
);

create table if not exists clientes (
  id integer generated by default as identity primary key,
  nombre text not null,
  telefono text,
  direccion text,
  tipo text not null default 'cliente' check (tipo in ('cliente', 'revendedor')),
  descuento numeric(6,2),
  notas text,
  creado timestamp not null default (now() at time zone 'America/Argentina/Buenos_Aires')
);

create table if not exists ventas (
  id integer generated by default as identity primary key,
  fecha timestamp not null,
  cliente_id integer references clientes(id),
  cliente_nombre text,
  tipo_precio text not null default 'publico',
  medio_pago text,
  entrega text,
  subtotal numeric(14,2) not null default 0,
  descuento numeric(14,2) not null default 0,
  recargo numeric(14,2) not null default 0,
  envio numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  costo numeric(14,2) not null default 0,
  notas text,
  origen text not null default 'local',
  tn_order_id text unique,
  anulada boolean not null default false
);
create index if not exists ventas_fecha_idx on ventas (fecha);

create table if not exists venta_items (
  id integer generated by default as identity primary key,
  venta_id integer not null references ventas(id) on delete cascade,
  producto_id integer references productos(id),
  descripcion text,
  cantidad numeric(12,2) not null,
  precio numeric(14,2) not null,
  costo numeric(14,2) not null default 0
);
create index if not exists venta_items_venta_idx on venta_items (venta_id);

create table if not exists cc_movimientos (
  id integer generated by default as identity primary key,
  cliente_id integer not null references clientes(id),
  fecha timestamp not null,
  tipo text not null check (tipo in ('cargo', 'pago')),
  monto numeric(14,2) not null,
  descripcion text,
  venta_id integer references ventas(id),
  medio_pago text
);
create index if not exists cc_mov_cliente_idx on cc_movimientos (cliente_id);

create table if not exists gastos (
  id integer generated by default as identity primary key,
  fecha date not null,
  categoria text,
  descripcion text,
  monto numeric(14,2) not null,
  medio_pago text
);
create index if not exists gastos_fecha_idx on gastos (fecha);

create table if not exists stock_movs (
  id integer generated by default as identity primary key,
  producto_id integer not null references productos(id) on delete cascade,
  fecha timestamp not null,
  cantidad numeric(12,2) not null,
  motivo text,
  ref text
);
create index if not exists stock_movs_prod_idx on stock_movs (producto_id);

create table if not exists cierres (
  id integer generated by default as identity primary key,
  fecha date not null unique,
  efectivo_inicial numeric(14,2) not null default 0,
  efectivo_contado numeric(14,2),
  efectivo_esperado numeric(14,2),
  diferencia numeric(14,2),
  resumen jsonb,
  notas text,
  creado timestamp not null default (now() at time zone 'America/Argentina/Buenos_Aires')
);

create table if not exists config (
  clave text primary key,
  valor text
);

